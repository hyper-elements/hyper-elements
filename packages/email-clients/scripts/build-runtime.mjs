#!/usr/bin/env node
// Builds the runtime each preview file carries: src/runtime/main.ts and the email-renderer modules it draws with
// (src/runtime/renderer/, at the commit RUNTIME_SOURCE names), bundled by esbuild into one minified IIFE, written to
// src/runtime.generated.ts as a string with its sha256 (the shell's CSP lets only that script run). The generated
// file is committed, so the package builds without email-renderer.
//
// It also writes core's copy of what Outlook.com removes from a <style> it keeps (the selectors, at-rules and states
// its model drops), packages/core/src/writers/email/outlook-com-style.generated.ts, from the same modules: validate()
// builds its notes from it, so moving the pin moves them too.
//
//   node scripts/build-runtime.mjs           # write both
//   node scripts/build-runtime.mjs --check   # fail if either isn't what the sources build
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = `${root}src/runtime.generated.ts`;
const coreOut = fileURLToPath(new URL('../../core/src/writers/email/outlook-com-style.generated.ts', import.meta.url));
const renderer = `${root}src/runtime/renderer/clients/`;

export async function runtimeScript() {
  const result = await build({
    entryPoints: [`${root}src/runtime/main.ts`],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'chrome120',
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  });
  // Inline in a <script>: nothing in it may end the element.
  const script = assertInlineSafe(result.outputFiles[0].text.trimEnd().replace(/<\/(script)/gi, '<\\/$1'));
  const sha256 = createHash('sha256').update(script, 'utf8').digest('base64');
  return { script, sha256 };
}

/**
 * `script`, if it's safe inline in a <script>: no `</script`, and not both `<!--` and `<script` followed by a space,
 * `/` or `>`, which would put the HTML parser in its double-escaped state, so the shell's own </script> wouldn't end
 * it. (The runtime has `<!--` in its conditional-comment patterns.) Fails the build otherwise.
 */
export function assertInlineSafe(script) {
  if (/<\/script/i.test(script)) throw new Error('The runtime holds "</script": it would end the preview\'s script early.');
  if (script.includes('<!--') && /<script[\s/>]/i.test(script)) {
    throw new Error('The runtime holds "<!--" and "<script": inline, the HTML parser would read past the preview\'s </script>. Write the tag another way in the source (as "<" + "script").');
  }
  return script;
}

export function generated({ script, sha256 }) {
  return [
    '// Built by scripts/build-runtime.mjs from src/runtime/: don\'t edit. Regenerate with `pnpm build:runtime`.',
    'import type { Runtime } from "./shell";',
    '',
    `export const RUNTIME: Runtime = { sha256: ${JSON.stringify(sha256)}, script: ${JSON.stringify(script)} };`,
    '',
  ].join('\n');
}

/**
 * Core's outlook-com-style.generated.ts, from the Outlook.com model: its profile's selectors and at-rules
 * (support.json) and the states it takes only on a type (outlook-com.js's TYPE_ONLY). Fails where the model no
 * longer has them where this reads them, rather than writing a file that says less.
 */
export function outlookComStyle() {
  const profile = JSON.parse(readFileSync(`${renderer}support.json`, 'utf8')).profiles['outlook-com'];
  const typeOnly = /^const TYPE_ONLY = (\/.+\/[a-z]*);$/m.exec(readFileSync(`${renderer}outlook-com.js`, 'utf8'))?.[1];
  if (!Array.isArray(profile?.selectors) || !Array.isArray(profile?.atRules) || !typeOnly) {
    throw new Error("The Outlook.com model has moved what core's outlook-com-style.generated.ts is written from (support.json's selectors and atRules, outlook-com.js's TYPE_ONLY): update outlookComStyle() in scripts/build-runtime.mjs.");
  }
  return [
    "// Generated by packages/email-clients/scripts/build-runtime.mjs from email-renderer's Outlook.com model (its",
    "// support.json and outlook-com.js, at the commit email-clients' RUNTIME_SOURCE pins): don't edit. Regenerate with",
    '// `pnpm --filter @hyper-elements/email-clients build:runtime`.',
    '',
    '/** What Outlook.com removes from a <style> it keeps, as its model in email-renderer does. */',
    'export const OUTLOOK_COM_STYLE: { selectors: readonly string[]; atRules: readonly string[]; onTypeOnly: RegExp } = {',
    '  /** The selectors it drops wherever they are: a part each holds, in lowercase (`:not(`). */',
    `  selectors: ${JSON.stringify(profile.selectors)},`,
    '  /** The at-rules it removes, by name (`supports` for @supports). */',
    `  atRules: ${JSON.stringify(profile.atRules)},`,
    '  /** What a compound selector (in lowercase) takes only after a type: `a:hover`, not `.promo:hover`. */',
    `  onTypeOnly: ${typeOnly},`,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = [
    [out, 'src/runtime.generated.ts', generated(await runtimeScript())],
    [coreOut, "core's outlook-com-style.generated.ts", outlookComStyle()],
  ];
  if (process.argv.includes('--check')) {
    const stale = files.filter(([path, , text]) => readFileSync(path, 'utf8') !== text);
    for (const [, name] of stale) console.error(`${name} is out of date: run \`pnpm --filter @hyper-elements/email-clients build:runtime\``);
    if (stale.length) process.exit(1);
    console.info('src/runtime.generated.ts and core\'s outlook-com-style.generated.ts are up to date');
  } else {
    for (const [path, name, text] of files) {
      writeFileSync(path, text);
      console.info(`Wrote ${name} (${text.length} bytes)`);
    }
  }
}
